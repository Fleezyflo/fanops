# tests/test_check_locks.py — CI-UNIT-LOCKDRIFT negative controls for scripts/check-locks.sh.
#
# The guard refuses a PR that changes pyproject.toml dependencies without regenerating the hashed
# locks. It counts only what a lock is built from: the base dependencies plus the extras each lock's
# own pip-compile header names. [asr] is on no lock's header (nightly-only, MOL-197), so a change to it
# has nothing to regenerate and must pass. Before that fix the guard compared every extra and refused
# an [asr] change that no relock could satisfy. Each test drives the real script in a temp git repo:
# a base commit, a PR commit on top of it, then the guard against the base.
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "check-locks.sh"
# The two locks the guard reads, each with the header pip-compile writes (see scripts/lock-deps.sh).
_LOCK_EXTRAS = {"ci-unit.txt": "--extra=dev --extra=studio", "ci-e2e.txt": "--extra=dev --extra=transcribe"}
_PYPROJECT = """\
[project]
name = "demo"
version = "0"
dependencies = ["requests>=2.31"]

[project.optional-dependencies]
dev = ["pytest>=8.0"]
studio = ["flask>=3.0"]
transcribe = ["openai-whisper>=20231117"]
asr = ["demucs>=4.0", "faster-whisper>=1.0"]
"""
# No inherited GIT_* (a GIT_DIR would aim these commits at the real repo); python3 is this interpreter.
_ENV = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
_ENV["PATH"] = f"{Path(sys.executable).parent}{os.pathsep}{_ENV.get('PATH', '')}"


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false", *args],
        cwd=repo, env=_ENV, check=True, capture_output=True, text=True).stdout.strip()


def _guard_on_pr(repo: Path, old: str, new: str) -> subprocess.CompletedProcess:
    """Commit pyproject + both locks as the base, commit `old` -> `new` as the PR, run the guard on it."""
    (repo / "requirements").mkdir()
    for name, extras in _LOCK_EXTRAS.items():
        (repo / "requirements" / name).write_text(
            "#\n# This file is autogenerated by pip-compile with Python 3.12\n# by the following command:\n#\n"
            f"#    pip-compile --allow-unsafe {extras} --generate-hashes --output-file=requirements/{name}"
            " --strip-extras pyproject.toml\n#\nrequests==2.32.3\n", encoding="utf-8")
    (repo / "pyproject.toml").write_text(_PYPROJECT, encoding="utf-8")
    _git(repo, "init", "-q")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "base")
    base = _git(repo, "rev-parse", "HEAD")
    assert old in _PYPROJECT, old
    (repo / "pyproject.toml").write_text(_PYPROJECT.replace(old, new), encoding="utf-8")
    _git(repo, "commit", "-q", "-am", "pr")
    return subprocess.run(["bash", str(_SCRIPT), base], cwd=repo, env=_ENV, capture_output=True, text=True)


def test_locked_extra_change_without_relock_is_refused(tmp_path):
    r = _guard_on_pr(tmp_path, 'dev = ["pytest>=8.0"]', 'dev = ["pytest>=8.0", "ruff>=0.5"]')
    assert r.returncode == 1 and "REFUSED" in r.stderr, r.stdout + r.stderr


def test_base_dependency_change_without_relock_is_refused(tmp_path):
    r = _guard_on_pr(tmp_path, 'dependencies = ["requests>=2.31"]',
                     'dependencies = ["requests>=2.31", "pydantic>=2.7"]')
    assert r.returncode == 1 and "REFUSED" in r.stderr, r.stdout + r.stderr


def test_unlocked_extra_change_passes(tmp_path):
    r = _guard_on_pr(tmp_path, 'asr = ["demucs>=4.0", "faster-whisper>=1.0"]',
                     'asr = ["demucs>=4.0", "faster-whisper>=1.0", "av<19"]')
    assert r.returncode == 0 and "OK" in r.stdout, r.stdout + r.stderr
